export type AdminLocale = "en" | "bn";

export const ADMIN_LOCALE_COOKIE = "kpesh-admin-locale";

export async function getAdminLocale(): Promise<AdminLocale> {
  return (await cookies()).get(ADMIN_LOCALE_COOKIE)?.value === "bn" ? "bn" : "en";
}

