let currentLang = "bn";
const langToggle = document.getElementById("langToggle");
function setLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;
  document.body.style.fontFamily =
    lang === "bn"
      ? "'Hind Siliguri','DM Sans',sans-serif"
      : "'DM Sans','Hind Siliguri',sans-serif";
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (translations[lang][key]) el.innerHTML = translations[lang][key];
  });
  langToggle.textContent = lang === "bn" ? "EN" : "বাং";
  document.querySelector("#name").placeholder =
    lang === "bn" ? "নাম লিখুন" : "Enter your name";
  document.querySelector("#phone").placeholder =
    lang === "bn" ? "01XXXXXXXXX" : "01XXXXXXXXX";
  document.querySelector("#message").placeholder =
    lang === "bn"
      ? "যেমন: কত ওয়াটের সিস্টেম দরকার..."
      : "e.g. required system size and backup time...";
  document.getElementById("formFeedback").textContent = "";
}
langToggle.addEventListener("click", () =>
  setLanguage(currentLang === "bn" ? "en" : "bn"),
);
